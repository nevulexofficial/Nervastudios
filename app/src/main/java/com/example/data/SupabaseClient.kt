package com.example.data

import android.util.Log
import com.example.BuildConfig
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext
import okhttp3.Interceptor
import okhttp3.MediaType.Companion.toMediaType
import okhttp3.OkHttpClient
import okhttp3.Request
import okhttp3.RequestBody.Companion.toRequestBody
import okhttp3.Response
import java.io.IOException
import java.util.concurrent.TimeUnit

/**
 * Data class representing the result of testing connection to Supabase.
 */
data class SupabaseConnectionResult(
    val isSuccess: Boolean,
    val statusCode: Int = 0,
    val latencyMs: Long = 0L,
    val message: String = ""
)

/**
 * Utility class and connection manager for Supabase in NERVA FC.
 *
 * Reads SUPABASE_URL and SUPABASE_ANON_KEY from environment variables (System.getenv)
 * with automatic fallback to BuildConfig (generated by secrets-gradle-plugin via .env).
 *
 * Manages an optimized OkHttpClient with authentication interceptors, base endpoints,
 * PostgREST CRUD helpers, RPC execution, and connection diagnostics.
 */
class SupabaseClient private constructor(
    initialUrl: String? = null,
    initialAnonKey: String? = null
) {
    private var explicitUrl: String? = initialUrl?.trim()?.removeSuffix("/")
    private var explicitAnonKey: String? = initialAnonKey?.trim()

    /**
     * The resolved Supabase project URL.
     * Priority: Explicitly set > System.getenv("SUPABASE_URL") > BuildConfig.SUPABASE_URL
     */
    val supabaseUrl: String
        get() {
            explicitUrl?.takeIf { it.isNotBlank() }?.let { return it }
            val envUrl = try {
                System.getenv("SUPABASE_URL")
            } catch (_: Exception) {
                null
            }
            if (!envUrl.isNullOrBlank()) {
                return envUrl.trim().removeSuffix("/")
            }
            return try {
                BuildConfig.SUPABASE_URL.trim().removeSuffix("/")
            } catch (_: Exception) {
                DEFAULT_PLACEHOLDER_URL
            }
        }

    /**
     * The resolved Supabase Anon / Public Key.
     * Priority: Explicitly set > System.getenv("SUPABASE_ANON_KEY") > BuildConfig.SUPABASE_ANON_KEY
     */
    val supabaseAnonKey: String
        get() {
            explicitAnonKey?.takeIf { it.isNotBlank() }?.let { return it }
            val envKey = try {
                System.getenv("SUPABASE_ANON_KEY")
            } catch (_: Exception) {
                null
            }
            if (!envKey.isNullOrBlank()) {
                return envKey.trim()
            }
            return try {
                BuildConfig.SUPABASE_ANON_KEY.trim()
            } catch (_: Exception) {
                DEFAULT_PLACEHOLDER_KEY
            }
        }

    /**
     * Checks if Supabase credentials are valid and ready for live cloud communication.
     */
    val isConfigured: Boolean
        get() {
            val url = supabaseUrl
            val key = supabaseAnonKey
            return url.isNotBlank() &&
                    url.startsWith("http") &&
                    !url.contains("your-project") &&
                    key.isNotBlank() &&
                    !key.contains("your-anon-key") &&
                    key.length >= 20
        }

    val restEndpoint: String
        get() = "$supabaseUrl/rest/v1"

    val authEndpoint: String
        get() = "$supabaseUrl/auth/v1"

    val realtimeWebsocketUrl: String
        get() {
            val cleanHost = supabaseUrl
                .removePrefix("https://")
                .removePrefix("http://")
            return "wss://$cleanHost/realtime/v1/websocket?apikey=$supabaseAnonKey&vsn=1.0.0"
        }

    private val jsonMediaType = "application/json; charset=utf-8".toMediaType()

    /**
     * Dedicated OkHttpClient with auth interceptor injecting required Supabase headers.
     */
    val httpClient: OkHttpClient by lazy {
        OkHttpClient.Builder()
            .connectTimeout(10, TimeUnit.SECONDS)
            .readTimeout(10, TimeUnit.SECONDS)
            .writeTimeout(10, TimeUnit.SECONDS)
            .addInterceptor(Interceptor { chain ->
                val original = chain.request()
                val requestBuilder = original.newBuilder()
                    .header("apikey", supabaseAnonKey)
                    .header("Authorization", "Bearer $supabaseAnonKey")
                    .header("Accept", "application/json")

                // Add content-type if request has body and header not already set
                if (original.body != null && original.header("Content-Type") == null) {
                    requestBuilder.header("Content-Type", "application/json")
                }

                chain.proceed(requestBuilder.build())
            })
            .build()
    }

    /**
     * Performs a GET request to a Supabase PostgREST table or path.
     * @param path The relative table/view query (e.g., "multiplayer_presence?select=*&limit=10")
     *             or full path starting with "/"
     */
    suspend fun get(
        path: String,
        headers: Map<String, String> = emptyMap()
    ): Result<String> = withContext(Dispatchers.IO) {
        try {
            val fullUrl = buildFullUrl(path)
            val requestBuilder = Request.Builder().url(fullUrl)
            headers.forEach { (k, v) -> requestBuilder.header(k, v) }

            val response = httpClient.newCall(requestBuilder.build()).execute()
            response.use {
                val body = it.body?.string().orEmpty()
                if (it.isSuccessful) {
                    Result.success(body)
                } else {
                    Result.failure(IOException("Supabase GET error ${it.code}: $body"))
                }
            }
        } catch (e: Exception) {
            Log.e(TAG, "GET request failed on $path", e)
            Result.failure(e)
        }
    }

    /**
     * Performs a POST request to Supabase PostgREST.
     * @param path The relative table path (e.g., "multiplayer_lobbies")
     * @param jsonBody Raw JSON payload string
     * @param prefer PostgREST Prefer header (e.g., "return=representation" or "resolution=merge-duplicates")
     */
    suspend fun post(
        path: String,
        jsonBody: String,
        prefer: String? = "return=representation"
    ): Result<String> = withContext(Dispatchers.IO) {
        try {
            val fullUrl = buildFullUrl(path)
            val requestBuilder = Request.Builder()
                .url(fullUrl)
                .post(jsonBody.toRequestBody(jsonMediaType))

            if (!prefer.isNullOrBlank()) {
                requestBuilder.header("Prefer", prefer)
            }

            val response = httpClient.newCall(requestBuilder.build()).execute()
            response.use {
                val body = it.body?.string().orEmpty()
                if (it.isSuccessful) {
                    Result.success(body)
                } else {
                    Result.failure(IOException("Supabase POST error ${it.code}: $body"))
                }
            }
        } catch (e: Exception) {
            Log.e(TAG, "POST request failed on $path", e)
            Result.failure(e)
        }
    }

    /**
     * Performs a PATCH request to Supabase PostgREST.
     */
    suspend fun patch(
        path: String,
        jsonBody: String,
        prefer: String? = "return=representation"
    ): Result<String> = withContext(Dispatchers.IO) {
        try {
            val fullUrl = buildFullUrl(path)
            val requestBuilder = Request.Builder()
                .url(fullUrl)
                .patch(jsonBody.toRequestBody(jsonMediaType))

            if (!prefer.isNullOrBlank()) {
                requestBuilder.header("Prefer", prefer)
            }

            val response = httpClient.newCall(requestBuilder.build()).execute()
            response.use {
                val body = it.body?.string().orEmpty()
                if (it.isSuccessful) {
                    Result.success(body)
                } else {
                    Result.failure(IOException("Supabase PATCH error ${it.code}: $body"))
                }
            }
        } catch (e: Exception) {
            Log.e(TAG, "PATCH request failed on $path", e)
            Result.failure(e)
        }
    }

    /**
     * Performs a DELETE request to Supabase PostgREST.
     */
    suspend fun delete(path: String): Result<String> = withContext(Dispatchers.IO) {
        try {
            val fullUrl = buildFullUrl(path)
            val request = Request.Builder().url(fullUrl).delete().build()
            val response = httpClient.newCall(request).execute()
            response.use {
                val body = it.body?.string().orEmpty()
                if (it.isSuccessful) {
                    Result.success(body)
                } else {
                    Result.failure(IOException("Supabase DELETE error ${it.code}: $body"))
                }
            }
        } catch (e: Exception) {
            Log.e(TAG, "DELETE request failed on $path", e)
            Result.failure(e)
        }
    }

    /**
     * Executes a Supabase Database Function via Remote Procedure Call (RPC).
     */
    suspend fun rpc(
        functionName: String,
        paramsJson: String = "{}"
    ): Result<String> = withContext(Dispatchers.IO) {
        try {
            val url = "$restEndpoint/rpc/$functionName"
            val request = Request.Builder()
                .url(url)
                .post(paramsJson.toRequestBody(jsonMediaType))
                .build()

            val response = httpClient.newCall(request).execute()
            response.use {
                val body = it.body?.string().orEmpty()
                if (it.isSuccessful) {
                    Result.success(body)
                } else {
                    Result.failure(IOException("Supabase RPC $functionName error ${it.code}: $body"))
                }
            }
        } catch (e: Exception) {
            Log.e(TAG, "RPC $functionName failed", e)
            Result.failure(e)
        }
    }

    /**
     * Tests the live connection and latency to the configured Supabase instance.
     */
    suspend fun testConnection(): SupabaseConnectionResult = withContext(Dispatchers.IO) {
        if (!isConfigured) {
            return@withContext SupabaseConnectionResult(
                isSuccess = false,
                statusCode = 400,
                latencyMs = 0L,
                message = "Supabase no está configurado (URL o ANON_KEY pendientes en .env)."
            )
        }

        val startTime = System.currentTimeMillis()
        try {
            // Ping OpenAPI schema endpoint of PostgREST
            val request = Request.Builder()
                .url(restEndpoint)
                .get()
                .build()

            val response: Response = httpClient.newCall(request).execute()
            val latency = System.currentTimeMillis() - startTime
            response.use {
                if (it.isSuccessful || it.code == 200 || it.code == 404) {
                    SupabaseConnectionResult(
                        isSuccess = true,
                        statusCode = it.code,
                        latencyMs = latency,
                        message = "Conectado exitosamente a Supabase (${latency}ms)"
                    )
                } else {
                    SupabaseConnectionResult(
                        isSuccess = false,
                        statusCode = it.code,
                        latencyMs = latency,
                        message = "Respuesta inesperada de Supabase: HTTP ${it.code}"
                    )
                }
            }
        } catch (e: Exception) {
            val latency = System.currentTimeMillis() - startTime
            SupabaseConnectionResult(
                isSuccess = false,
                statusCode = 0,
                latencyMs = latency,
                message = "Error de conexión: ${e.localizedMessage ?: "No se pudo contactar a Supabase"}"
            )
        }
    }

    private fun buildFullUrl(path: String): String {
        return if (path.startsWith("http://") || path.startsWith("https://")) {
            path
        } else {
            val cleanPath = path.removePrefix("/")
            "$restEndpoint/$cleanPath"
        }
    }

    companion object {
        private const val TAG = "SupabaseClient"
        const val DEFAULT_PLACEHOLDER_URL = "https://your-project.supabase.co"
        const val DEFAULT_PLACEHOLDER_KEY = "your-anon-key-here"

        @Volatile
        private var instance: SupabaseClient? = null

        /**
         * Singleton accessor for default app-wide SupabaseClient.
         * Resolves credentials from System.getenv and BuildConfig.
         */
        fun getInstance(): SupabaseClient {
            return instance ?: synchronized(this) {
                instance ?: SupabaseClient().also { instance = it }
            }
        }

        /**
         * Explicitly initialize or reconfigure the singleton client with custom credentials.
         */
        fun initialize(url: String? = null, anonKey: String? = null): SupabaseClient {
            return synchronized(this) {
                val newClient = SupabaseClient(url, anonKey)
                instance = newClient
                newClient
            }
        }

        /**
         * Convenience factory to create an isolated client instance with custom settings.
         */
        fun create(url: String? = null, anonKey: String? = null): SupabaseClient {
            return SupabaseClient(url, anonKey)
        }
    }
}
